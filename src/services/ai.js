import OpenAI from "openai";
import { config } from "../const/config.js";

const openai = new OpenAI({
  apiKey: config.deepseekKey,
  baseURL: "https://api.deepseek.com",
});

export async function askOpenAI(userQuestion, faqContext) {
  const contextText = faqContext || "Контекст временно недоступен.";
  const responce = await openai.chat.completions.create({
    model: config.aiModel,
    messages: [
      {
        role: "system",
        content: `Ты — оператор-помощник в лицее. Твоя задача — отвечать на вопросы строго на основе предоставленной базы знаний.

База знаний состоит из старых материалов PDF и нового контекста сайта. Считай их единым источником: данные из PDF и сайта должны дополнять друг друга. Если часть ответа есть в PDF, а часть в данных сайта, объедини их в один полный ответ. Не игнорируй новый контекст сайта и не игнорируй старые PDF.

Если источники дают похожую информацию, используй более полную и конкретную формулировку. Если есть небольшие различия, не придумывай причину различий: отвечай аккуратно и при необходимости советуй уточнить у администрации. Контакты, телефоны, адреса, сроки, документы и условия поступления бери из предоставленного контекста.

Отвечай кратко и четко, обычно 2-4 предложения. Не говори пользователю, из какого файла или раздела взяты данные. Не упоминай слова "FAQ", "PDF", "контекст" или "сайт", если пользователь сам не спрашивает про источники данных.

Если в объединенной базе знаний действительно нет ответа на вопрос, дай номер администрации. Если номер администрации тоже не найден, верни NOT_FOUND. Не придумывай факты от себя.

Отвечай в Markdown:
- выделяй **важные данные**: телефоны, адреса, сроки, документы;
- используй списки через "- " для перечислений;
- не меняй логику приложения, только форматируй ответ.`,
      },
      {
        role: "user",
        content: `Объединенная база знаний лицея:\n${contextText}\n\nВопрос пользователя: ${userQuestion}`,
      },
    ],
    temperature: 0.1,
  });

  return responce.choices[0].message.content.trim();
}
